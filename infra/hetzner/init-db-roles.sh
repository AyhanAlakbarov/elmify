#!/usr/bin/env sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  DO \$\$
  BEGIN
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${POSTGRES_ENGINE_USER}') THEN
      CREATE ROLE "${POSTGRES_ENGINE_USER}" LOGIN PASSWORD '${POSTGRES_ENGINE_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${POSTGRES_WEB_USER}') THEN
      CREATE ROLE "${POSTGRES_WEB_USER}" LOGIN PASSWORD '${POSTGRES_WEB_PASSWORD}';
    END IF;
  END
  \$\$;
  GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${POSTGRES_ENGINE_USER}", "${POSTGRES_WEB_USER}";
EOSQL
