export const STRINGS: Record<Lang, Record<StringKey, string>> = { az: AZ, tr: TR, ru: RU, en: EN };

/** "az-AZ" -> "az"; anything unknown -> "en". */
export function defaultLang(browserLanguage: string): Lang {
  const base = ((browserLanguage ?? "").toLowerCase().split(/[-_]/)[0] ?? "");
  return (LANGS as readonly string[]).includes(base) ? (base as Lang) : "en";
}

export function t(lang: Lang, key: StringKey, vars: Record<string, string> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) => vars[name] ?? whole);
}

