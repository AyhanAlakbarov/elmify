/** A FILE_FIELDS document's name; an unknown one is "Document", never the code. */
export function kindLabel(lang: Lang, kind: string): string {
  const key = `k_${kind}` as StringKey;
  return t(lang, key in EN ? key : "k_other");
}

/** The refused bundle's one line: what to do, then why (a clause, never a second
 *  instruction -- final review M5). An unknown reason adds no clause. */
export function bundleText(lang: Lang, code: string): string {
  const key = `nb_${code}` as StringKey;
  return key in EN ? `${t(lang, "n_bundle_failed")} ${t(lang, key)}` : t(lang, "n_bundle_failed");
}

/** The sentence for a note code; an unknown code gets the generic one, never the code. */
export function noteText(lang: Lang, code: string): string {
  const key = `n_${code}` as StringKey;
  return t(lang, key in EN ? key : "n_other");
}
