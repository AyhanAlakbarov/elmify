"""`deadline_for` as a page writes it -> the condition vocabulary (spec 9.2).

Pure. Both vocabularies are data: the phrase patterns in
docs/research/deadline-condition-terms.csv, the country names in
docs/research/country-labels.csv (Wikidata labels and demonyms, CC0,
regenerated by `manage.py refresh_country_labels`). Nothing unmapped is ever
guessed: it is `OTHER:<text>`, shown to the student as written.

A negated place is the sharpest case of that rule: "residents of non-EU
countries" once came out `RESIDENCE:EU`, the exact inverse of the page. So a
place preceded by `non-`, any term row whose condition is the bare `OTHER`
(outside, other than, except ... -- data, like every other term), and a
residence phrase that also matched another term all refuse to map.
"""

from __future__ import annotations

import csv
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from functools import cache
from pathlib import Path

from apps.funding.regions import REGIONS

_DOCS = Path(__file__).resolve().parents[2] / "docs" / "research"
#: validity keeps a condition in a CharField-sized string; so do we.
_OTHER_MAX = 60
#: A term row with this bare condition refuses to map the whole phrase.
REFUSE = "OTHER"
_ISO_LIST = re.compile(r"[A-Z]{2}(?:,[A-Z]{2})*")
_TOKEN = re.compile(r"[A-Z_]+")
_TOKEN_PREFIXES = frozenset({"APPLICANT_CLASS", "FUNDING", "ROUTE", "DESCENT"})
#: "non-India", "non India" -- "nonindian" is not a word boundary and never matches.
_NEGATED = re.compile(r"(?<!\w)non[- ]$")


@dataclass(frozen=True)
class ConditionTerm:
    pattern: str
    condition: str
    regex: re.Pattern[str] = field(init=False, compare=False, repr=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "regex", re.compile(self.pattern, re.IGNORECASE))


@cache
def default_terms() -> tuple[ConditionTerm, ...]:
    with (_DOCS / "deadline-condition-terms.csv").open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    for row in rows:
        if not (row["pattern"] and row["condition"] and row["source"] and row["verified_on"]):
            raise ValueError(f"deadline-condition-terms row is incomplete: {row}")
    return tuple(ConditionTerm(row["pattern"], row["condition"]) for row in rows)


@cache
def default_countries() -> dict[str, str]:
    """Label -> ISO code, minus every label two countries share.

    "Korean" is a demonym of both KP and KR; keeping either is a guess, so the
    label is dropped and such a phrase falls to OTHER.
    """
    codes: dict[str, set[str]] = {}
    with (_DOCS / "country-labels.csv").open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            codes.setdefault(row["label"].casefold(), set()).add(row["iso2"].upper())
    return {label: next(iter(found)) for label, found in codes.items() if len(found) == 1}


def _passthrough(raw: str) -> str | None:
    """`raw` when it already is the normalised form, validated per prefix.

    The prefix is case-insensitive; a value is not: "residence: no" is prose,
    never Norway.
    """
    written, sep, value = raw.partition(":")
    prefix = written.strip().upper()
    value = value.strip()
    if written.strip() == "OPEN":
        # validity._is_unconditional and eligibility.decide both read an OPEN
        # row as "open to all"; sent to OTHER it would match nobody and the
        # page's general date would be lost. Upper-case only: "open" is prose.
        return f"OPEN:{value[:_OTHER_MAX]}" if value else "OPEN"
    if not sep or not value:
        return None
    if prefix in ("NATIONALITY", "RESIDENCE"):
        valid = bool(_ISO_LIST.fullmatch(value)) or value in REGIONS
    elif prefix == "ROUND":
        valid = value.isascii() and value.isdigit()
    elif prefix in _TOKEN_PREFIXES:
        valid = bool(_TOKEN.fullmatch(value))
    elif prefix == "OTHER":
        return f"OTHER:{value[:_OTHER_MAX]}"
    else:
        valid = False
    return f"{prefix}:{value}" if valid else None


@cache
def _label_pattern(labels: tuple[str, ...]) -> re.Pattern[str]:
    # Longest first: at any one position the alternation tries the longer label
    # first, and a scan never re-enters a matched span, so "Papua New Guinea"
    # is never also "Guinea".
    alternation = "|".join(re.escape(label) for label in sorted(labels, key=len, reverse=True))
    return re.compile(rf"(?<!\w)(?:{alternation})(?!\w)")


def _countries_in(text: str, countries: Mapping[str, str]) -> list[str] | None:
    """ISO codes of every country the text names, in the order it names them.

    None when any named country is negated ("non-Indian"): the phrase then
    says who is *not* meant, which no country list expresses.
    """
    folded_map = {label.casefold(): code for label, code in countries.items() if label}
    if not folded_map:
        return []
    folded = text.casefold()
    codes: list[str] = []
    for match in _label_pattern(tuple(sorted(folded_map))).finditer(folded):
        if _NEGATED.search(folded[: match.start()]):
            return None
        codes.append(folded_map[match.group()])
    return list(dict.fromkeys(codes))


def _region_in(text: str) -> str | None:
    """The first REGIONS key the text names; "" for none, None when negated."""
    folded = text.casefold()
    for key, region in REGIONS.items():
        for name in (key, region.name):
            for match in re.finditer(rf"(?<!\w){re.escape(name.casefold())}(?!\w)", folded):
                if _NEGATED.search(folded[: match.start()]):
                    return None
                return key
    return ""


def normalise_condition(
    text: str,
    *,
    countries: Mapping[str, str] | None = None,
    terms: Sequence[ConditionTerm] | None = None,
) -> str:
    raw = " ".join((text or "").split())
    if not raw or raw.upper() == "ALL":
        return "ALL"
    already = _passthrough(raw)
    if already is not None:
        return already
    countries = default_countries() if countries is None else countries
    terms = default_terms() if terms is None else terms
    other = f"OTHER:{raw[:_OTHER_MAX]}"

    matched = [(match, term) for term in terms if (match := term.regex.search(raw))]
    if any(term.condition == REFUSE for _match, term in matched):
        return other
    residence = any(term.condition == "RESIDENCE:*" for _match, term in matched)
    if residence and len(matched) > 1:
        # "EU residents", "residents of non-EU countries": which term binds the
        # place is a guess, and one of the readings may be the inverse.
        return other
    if matched and not residence:
        match, term = min(matched, key=lambda pair: (pair[0].start(), -len(pair[0].group())))
        return term.condition.format(*match.groups())

    prefix = "RESIDENCE" if residence else "NATIONALITY"
    codes = _countries_in(raw, countries)
    if codes is None:
        return other
    region = _region_in(raw)
    if region is None:
        return other
    if codes:
        return f"{prefix}:{','.join(codes)}"
    if region and prefix == "RESIDENCE":
        return f"RESIDENCE:{region}"
    return other
